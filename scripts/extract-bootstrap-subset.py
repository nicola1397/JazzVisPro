"""Writes src/assets/vendor-bootstrap-subset.css: Bootstrap's reboot plus only the classes the
app uses, so the full 230 KB stylesheet (and the unused 80 KB script) can go.

Usage: python3 scripts/extract-bootstrap-subset.py path/to/bootstrap.min.css
Bootstrap v5.3.3, MIT licence (https://github.com/twbs/bootstrap/blob/main/LICENSE)."""
import re, sys

src = open(sys.argv[1]).read()
USED = {
    # grid (Player progression steps, Progress page)
    'row', 'col', 'col-2', 'col-4', 'col-8', 'col-12', 'col-sm', 'col-sm-auto', 'col-sm-2', 'col-sm-5',
    'col-sm-7', 'col-sm-10', 'col-lg-1', 'col-lg-3', 'col-lg-4', 'g-1', 'g-2', 'gx-2', 'gy-2',
    'order-1', 'order-2', 'order-3', 'order-sm-2', 'order-sm-3',
    # utilities
    'd-flex', 'd-lg-none', 'align-items-center', 'justify-content-center', 'justify-content-end',
    'flex-grow-1', 'gap-2', 'm-0', 'mb-0', 'mb-4', 'mt-3', 'mt-4', 'p-0', 'p-1', 'pe-1', 'w-100',
    'text-center', 'rounded', 'bg-black', 'bg-opacity-25', 'h3',
    # components whose class names the app reuses
    'navbar', 'modal-content',
}

def blocks(css):
    """Yield (prelude, body) for each top-level block."""
    i, n = 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0: return
        prelude = css[i:j].strip()
        depth, k = 1, j + 1
        while depth:
            if css[k] == '{': depth += 1
            elif css[k] == '}': depth -= 1
            k += 1
        yield prelude, css[j + 1:k - 1]
        i = k

def keep(selector):
    parts = [p.strip() for p in selector.split(',')]
    def ok(p):
        m = re.fullmatch(r'\.([\w-]+)(\s*>\s*\*)?', p)
        return bool(m) and m.group(1) in USED
    return all(ok(p) for p in parts) or (any(ok(p) for p in parts) and all(re.fullmatch(r'\.[\w-]+(\s*>\s*\*)?', p) for p in parts))

end = src.index('[hidden]{display:none!important}') + len('[hidden]{display:none!important}')
reboot = src[src.index(':root,[data-bs-theme=light]'):end]
# drop the dark-theme variable block: the app has its own palette
reboot = re.sub(r'\[data-bs-theme=dark\]\{[^}]*\}', '', reboot)

out = []
for prelude, body in blocks(src[end:]):
    if prelude.startswith('@media'):
        inner = [f'{sel}{{{b}}}' for sel, b in blocks(body) if keep(sel)]
        if inner: out.append(f'{prelude}{{{"".join(inner)}}}')
    elif not prelude.startswith('@') and keep(prelude):
        # keep only the used selectors of a grouped rule
        sels = [p.strip() for p in prelude.split(',') if re.fullmatch(r'\.([\w-]+)(\s*>\s*\*)?', p.strip()) and re.match(r'\.([\w-]+)', p.strip()).group(1) in USED]
        out.append(f'{",".join(sels)}{{{body}}}')

header = '/*! Subset of Bootstrap v5.3.3 (https://getbootstrap.com/) · MIT licence · generated by scripts/extract-bootstrap-subset.py */\n'
open('src/assets/vendor-bootstrap-subset.css', 'w').write(header + reboot + '\n' + '\n'.join(out) + '\n')
print('reboot', len(reboot), 'bytes; rules', len(out), '; total', len(header) + len(reboot) + sum(map(len, out)), 'bytes')
